        assert page.evaluate('albumCurrentItems().length===0')
        page.reload()
        page.locator('.album-tile').first.click()
        page.locator('#albBody [data-album-item]').first.click()
        expect(page.locator('#viewerCommentsButton')).to_contain_text('댓글 1')
        page.get_by_role('button', name='사진 확대 닫기').click()
        passed('Viewer actions, photo-only mode, likes filter/cancel and comment persistence work')

        page.locator('#addAlbumFriend').click()
        page.locator('.friend-pick-row').first.click()
        page.locator('#inviteFriendsSubmit').click()
        expect(page.locator('#inviteFriendsStatus')).to_contain_text('초대 완료')
        page.locator('#inviteFriendsSubmit').click()
