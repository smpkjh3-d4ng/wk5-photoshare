        passed('Save checkbox updates option/submit counts and IDs, including own-only zero handling')

        page.locator('[data-photo-filter=all]').click()
        page.locator('#albBody [data-album-item]').first.click()
        expect(page.locator('.detail-actions button')).to_have_text(['저장', '공유', '댓글 0', '삭제'])
        expect(page.locator('.detail-top .detail-info-small')).to_be_visible()
        page.locator('.detail-like').click()
        liked_id = page.evaluate('photoViewerItems[photoViewerIndex].id')
